#!/usr/bin/env python3
"""Mozilla's root list for web_tls on Android (Web ADR 0017).

    python3 tools/update_roots.py           # download curl's extract, check its SHA-256, write the two files
    python3 tools/update_roots.py --check   # the committed files agree with each other (no network; CI)

packages/web_tls/c/roots_mozilla.pem is curl's extract of Mozilla's root store (https://curl.se/ca/cacert.pem),
byte for byte; packages/web_tls/c/roots_mozilla.h is the same PEM as a C string, with its date and SHA-256.
"""

import hashlib
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PEM = os.path.join(ROOT, "packages", "web_tls", "c", "roots_mozilla.pem")
HEADER = os.path.join(ROOT, "packages", "web_tls", "c", "roots_mozilla.h")
URL = "https://curl.se/ca/cacert.pem"


def extract_date(pem: bytes) -> str:
    m = re.search(rb"^## Certificate data from Mozilla as of: (.+)$", pem, re.M)
    if not m:
        sys.exit("update_roots: the extract does not say its date")
    return m.group(1).decode().strip()


def certificates(pem: bytes) -> bytes:
    """Only the certificates: curl's comments and blank lines are left out of the C string."""
    blocks = re.findall(rb"-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----\n", pem, re.S)
    if len(blocks) < 100:
        sys.exit("update_roots: %d certificates, fewer than a root store has" % len(blocks))
    return b"".join(blocks)


def header(pem: bytes) -> str:
    digest = hashlib.sha256(pem).hexdigest()
    date = extract_date(pem)
    body = certificates(pem)
    count = body.count(b"-----BEGIN CERTIFICATE-----")
    lines = [
        "/* Generated by tools/update_roots.py from roots_mozilla.pem: do not edit (Web ADR 0017).",
        "   Mozilla's root store, as curl extracts it (%s), MPL 2.0 (COPYING.MPL)." % URL,
        "   The extract: %s; SHA-256 %s; %d certificates. */" % (date, digest, count),
        "#ifndef WT_ROOTS_MOZILLA_H",
        "#define WT_ROOTS_MOZILLA_H",
        '#define WT_MOZILLA_ROOTS_DATE "%s"' % date,
        '#define WT_MOZILLA_ROOTS_SHA256 "%s"' % digest,
        "static const char wt_mozilla_roots[] =",
    ]
    for line in body.decode("ascii").splitlines():
        lines.append('    "%s\\n"' % line)
    lines[-1] += ";"
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "CeeSafe.Web update_roots"})
    with urllib.request.urlopen(request, timeout=60) as r:
        return r.read()


def main() -> None:
    if "--check" in sys.argv[1:]:
        with open(PEM, "rb") as f:
            pem = f.read()
        with open(HEADER) as f:
            written = f.read()
        if written != header(pem):
            sys.exit("update_roots: roots_mozilla.h is not made from roots_mozilla.pem: run tools/update_roots.py")
        print("update_roots: roots_mozilla.h matches roots_mozilla.pem (%s)" % extract_date(pem))
        return
    pem = fetch(URL)
    published = fetch(URL + ".sha256").split()[0].decode()
    if hashlib.sha256(pem).hexdigest() != published:
        sys.exit("update_roots: the download's SHA-256 is not the one curl.se publishes")
    with open(PEM, "wb") as f:
        f.write(pem)
    with open(HEADER, "w") as f:
        f.write(header(pem))
    print("update_roots: Mozilla's roots of %s written" % extract_date(pem))


if __name__ == "__main__":
    main()
