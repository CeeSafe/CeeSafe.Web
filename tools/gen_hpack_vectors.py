#!/usr/bin/env python3
"""Generates packages/web_http2/tests/rfc7541.cee from RFC 7541's text: every example of Appendix C.2-C.6 (the encoded
block, the decoded header list, and the dynamic table's size after decoding), as test data. The tests decode each
block and compare with the RFC's list and size, so the expected values are the RFC's, not the code's.

    python3 tools/gen_hpack_vectors.py rfc7541.txt
"""

import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "packages", "web_http2", "tests", "rfc7541.cee")
SECTIONS = ["C.2.1", "C.2.2", "C.2.3", "C.2.4", "C.3.1", "C.3.2", "C.3.3", "C.4.1", "C.4.2", "C.4.3",
            "C.5.1", "C.5.2", "C.5.3", "C.6.1", "C.6.2", "C.6.3"]


def clean(text):
    lines = []
    for line in text.replace("\f", "").splitlines():
        if re.match(r"^Peon & Ruellan\s", line) or re.match(r"^RFC 7541\s+HPACK", line):
            continue
        lines.append(line)
    return lines


def block_after(lines, i, heading):
    """The non-blank lines after `heading` (searched from line i), up to the next blank line after content."""
    while lines[i].strip() != heading:
        i += 1
    i += 1
    while not lines[i].strip():
        i += 1
    out = []
    while i < len(lines) and lines[i].strip():
        out.append(lines[i])
        i += 1
    return out, i


def section(lines, name):
    start = next(i for i, l in enumerate(lines) if l.startswith(name + ".  "))
    later = [i for i, l in enumerate(lines) if re.match(r"^C\.\d(\.\d)?\.  ", l) and i > start]
    end = later[0] if later else len(lines)
    part = lines[start:end]
    hexlines, _ = block_after(part, 0, "Hex dump of encoded data:")
    block = "".join(l.split("|")[0].replace(" ", "") for l in hexlines)
    decoded, _ = block_after(part, 0, "Decoded header list:")
    fields = []
    for l in decoded:
        l = l.strip()
        cut = l.index(": ", 1)  # a pseudo-header's name starts with ':'
        fields.append((l[:cut], l[cut + 2:]))
    sizes = [int(m.group(1)) for m in (re.search(r"Table size:\s*(\d+)", l) for l in part) if m]
    if not sizes and any("Dynamic table (after decoding): empty." in l for l in part):
        sizes = [0]
    assert len(sizes) == 1, f"{name}: {sizes}"
    return block, fields, sizes[0]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    raw = open(sys.argv[1], "rb").read()
    lines = clean(raw.decode("ascii"))
    digest = hashlib.sha256(raw).hexdigest()
    out = [
        "// Generated by tools/gen_hpack_vectors.py from RFC 7541's text (sha256 " + digest[:16] + "…); do not edit.",
        "// Appendix C.2-C.6: each example's encoded block, decoded header list (one `name: value` per line) and the",
        "// dynamic table's size after decoding.",
        "",
        "/// One example of RFC 7541 Appendix C.",
        "struct Example {",
        "    block: Vector<u8>;",
        "    expected: Vector<u8>;",
        "    tableSize: u32;",
        "}",
        "",
    ]
    for name in SECTIONS:
        block, fields, size = section(lines, name)
        listing = "\\n".join(f"{n}: {v}" for n, v in fields) + "\\n"
        assert '"' not in listing and "\\\\" not in listing
        ident = "example" + name.replace(".", "_")
        out += [
            f"/// RFC 7541 Appendix {name}.",
            f"fn {ident}() -> Result<Example, TestFailure> =>",
            f'    example("{block}", "{listing}", {size});',
            "",
        ]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    subprocess.run([os.environ.get("CEESAFEC", "ceesafec"), "fmt", OUT], check=True)
    print(f"gen_hpack_vectors: wrote {os.path.relpath(OUT, ROOT)}: {len(SECTIONS)} examples (RFC 7541 sha256 {digest})")


if __name__ == "__main__":
    main()
