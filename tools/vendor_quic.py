#!/usr/bin/env python3
"""Vendors ngtcp2 and nghttp3 for web_quic and web_http3 (Web ADR 0014 §3.2).

usage: python3 tools/vendor_quic.py [--from DIR]

For each library it:
- downloads the release tarball (or takes it from --from DIR), and checks it against the SHA-256 recorded below;
- copies only the sources that are compiled, their headers and their licences, into third_party/<name>-<version>/;
- writes a portable config.h there (its own directory, config/, which the package's manifest puts on the include path);
- writes one wrapper .c per vendored source into the package's c/vendor/: it defines what the libraries' build would
  (HAVE_CONFIG_H, the static-library macro) and #includes the untouched original, since manifests pass no defines;
- rewrites the package manifest's `c = [...]` line to list the package's shim and the wrappers.

A version change is a run of this script and a commit, never an edit by hand. The tarballs' digests are GitHub's
(the release assets' `digest`, checked 2026-11-09).
"""
import argparse, hashlib, io, os, pathlib, shutil, sys, tarfile, tempfile, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent

LIBRARIES = [
    {
        "name": "ngtcp2", "version": "1.26.0", "package": "web_quic", "shim": "c/quic_shim.c",
        "url": "https://github.com/ngtcp2/ngtcp2/releases/download/v1.26.0/ngtcp2-1.26.0.tar.xz",
        "sha256": "7804aa0fa1c39942ba322a90805824c37231f7675b08d0c3cc4332858a7b085e",
        "static": "NGTCP2_STATICLIB",
        # (directory in the tarball, files to compile, other files to copy)
        "copy": [
            ("lib", "*.c", "*.h"),
            ("lib/includes/ngtcp2", None, "*.h"),
            ("crypto", "shared.c", "shared.h"),
            ("crypto/ossl", "ossl.c", None),
            ("crypto/includes/ngtcp2", None, "ngtcp2_crypto.h ngtcp2_crypto_ossl.h"),
        ],
    },
    {
        "name": "nghttp3", "version": "1.19.0", "package": "web_http3", "shim": "c/h3_shim.c",
        "url": "https://github.com/ngtcp2/nghttp3/releases/download/v1.19.0/nghttp3-1.19.0.tar.xz",
        "sha256": "228e17f5cc3d4de7bfced9912bd09de30e7f45741cc47503cf88d3fa9209e155",
        "static": "NGHTTP3_STATICLIB",
        "copy": [
            ("lib", "*.c", "*.h"),
            ("lib/includes/nghttp3", None, "*.h"),
            ("lib/sfparse", "sfparse.c", "sfparse.h COPYING"),
        ],
    },
]

LICENCES = ["COPYING", "AUTHORS"]

# What CMake's checks would find on each system the project builds on (Linux with glibc, macOS, Windows). Only
# optional faster paths depend on these: each library has a portable fallback (ngtcp2_net.h, nghttp3_conv.h).
CONFIG = """/* GENERATED by tools/vendor_quic.py: edit that, not this file. */
/* The libraries' config.h (their cmakeconfig.h.in), for the systems CeeSafe.Web builds on (Web ADR 0014 §3.2). */
#ifndef CEESAFE_WEB_{guard}_CONFIG_H
#define CEESAFE_WEB_{guard}_CONFIG_H

#if defined(_WIN32)
/* The libraries test WIN32, which compilers do not define. */
#  ifndef WIN32
#    define WIN32 1
#  endif
#  include <stddef.h>
#  define ssize_t ptrdiff_t
#  define HAVE_DECL_BE64TOH 0
#  define HAVE_DECL_BSWAP_64 0
#else
#  define HAVE_ARPA_INET_H 1
#  define HAVE_NETINET_IN_H 1
#  define HAVE_NETINET_IP_H 1
#  define HAVE_UNISTD_H 1
#  if defined(__linux__)
#    define HAVE_ENDIAN_H 1
#    define HAVE_BYTESWAP_H 1
#    define HAVE_DECL_BE64TOH 1
#    define HAVE_DECL_BSWAP_64 1
#    define HAVE_EXPLICIT_BZERO 1 /* declared under _GNU_SOURCE, which each wrapper defines first */
#  else /* macOS: libkern/OSByteOrder.h, chosen by the libraries themselves */
#    define HAVE_DECL_BE64TOH 0
#    define HAVE_DECL_BSWAP_64 0
#  endif
#endif

#if defined(__BYTE_ORDER__) && defined(__ORDER_BIG_ENDIAN__) && __BYTE_ORDER__ == __ORDER_BIG_ENDIAN__
#  define WORDS_BIGENDIAN 1
#endif

#endif
"""

WRAPPER = """/* GENERATED by tools/vendor_quic.py: edit that, not this file. */
/* {source} of {name} {version}, compiled as its own build would: with its config.h, as a static library. */
#if defined(__linux__) && !defined(_GNU_SOURCE)
#  define _GNU_SOURCE 1 /* be64toh and explicit_bzero under -std=c11, before any system header */
#endif
#define HAVE_CONFIG_H 1
#define {static} 1
#include "{path}"
"""


def fetch(lib, source_dir):
    name = f"{lib['name']}-{lib['version']}.tar.xz"
    if source_dir:
        data = (pathlib.Path(source_dir) / name).read_bytes()
    else:
        with urllib.request.urlopen(lib["url"]) as r:
            data = r.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != lib["sha256"]:
        sys.exit(f"vendor_quic: {name} has SHA-256 {digest}, not {lib['sha256']}")
    return data


def safe_members(archive, top):
    for m in archive.getmembers():
        p = pathlib.PurePosixPath(m.name)
        if p.is_absolute() or ".." in p.parts or not (m.isfile() or m.isdir()):
            sys.exit(f"vendor_quic: refusing tarball member {m.name}")
        if p.parts and p.parts[0] != top:
            sys.exit(f"vendor_quic: tarball member {m.name} outside {top}/")
        yield m


def vendor(lib, source_dir):
    top = f"{lib['name']}-{lib['version']}"
    data = fetch(lib, source_dir)
    dest = ROOT / "third_party" / top
    with tempfile.TemporaryDirectory() as work:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:xz") as archive:
            archive.extractall(work, members=list(safe_members(archive, top)))
        src = pathlib.Path(work) / top
        if dest.exists():
            shutil.rmtree(dest)
        compiled = []
        for directory, sources, others in lib["copy"]:
            for patterns, compile_them in ((sources, True), (others, False)):
                if not patterns:
                    continue
                for pattern in patterns.split():
                    files = sorted((src / directory).glob(pattern))
                    if not files:
                        sys.exit(f"vendor_quic: {top}/{directory}/{pattern} matched nothing")
                    for f in files:
                        if f.name.endswith("_test.c") or f.name.endswith("_test.h"):
                            continue
                        target = dest / directory / f.name
                        target.parent.mkdir(parents=True, exist_ok=True)
                        shutil.copyfile(f, target)
                        if compile_them:
                            compiled.append(target)
        for name in LICENCES:
            shutil.copyfile(src / name, dest / name)
    (dest / "config").mkdir()
    (dest / "config" / "config.h").write_text(CONFIG.format(guard=lib["name"].upper()))
    package = ROOT / "packages" / lib["package"]
    wrappers = package / "c" / "vendor"
    if wrappers.exists():
        shutil.rmtree(wrappers)
    wrappers.mkdir(parents=True)
    listed = []
    for f in compiled:
        relative = f.relative_to(dest)
        wrapper = wrappers / ("_".join(relative.parts))
        path = os.path.relpath(f, wrappers).replace(os.sep, "/")
        wrapper.write_text(WRAPPER.format(source=relative.as_posix(), name=lib["name"], version=lib["version"],
                                          static=lib["static"], path=path))
        listed.append(wrapper.relative_to(package).as_posix())
    manifest = package / "ceesafe.toml"
    lines = manifest.read_text().splitlines()
    c_line = "c = [" + ", ".join(f'"{p}"' for p in [lib["shim"]] + listed) + "]"
    for i, line in enumerate(lines):
        if line.startswith("c = ["):
            lines[i] = c_line
            break
    else:
        sys.exit(f"vendor_quic: {manifest} has no `c = [...]` line to rewrite")
    manifest.write_text("\n".join(lines) + "\n")
    return top, len(compiled)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="source_dir", help="a directory holding the release tarballs, instead of downloading")
    args = ap.parse_args()
    rows = []
    for lib in LIBRARIES:
        top, n = vendor(lib, args.source_dir)
        rows.append(f"| `{top}` | {lib['url']} | `{lib['sha256']}` | MIT (`{top}/COPYING`) | {n} | `{lib['package']}` |")
        print(f"vendor_quic: {top}: {n} sources, wrappers in packages/{lib['package']}/c/vendor/")
    (ROOT / "third_party" / "README.md").write_text(
        "# Vendored C\n\n"
        "GENERATED by `tools/vendor_quic.py`: edit that, not this file.\n\n"
        "The QUIC and HTTP/3 libraries, as released, with only the files that are compiled, their headers and their\n"
        "licences (Web ADR 0014 §3.2). Each package's `c/vendor/` holds one wrapper per source, which sets the macros\n"
        "the libraries' own build would and includes the original. `config/config.h` is written by the script.\n\n"
        "| Library | Release | SHA-256 | Licence | Sources | Compiled by |\n|---|---|---|---|---|---|\n"
        + "\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
