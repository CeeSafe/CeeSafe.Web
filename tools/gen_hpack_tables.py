#!/usr/bin/env python3
"""Generates packages/web_http2/src/tables.cee from the text of RFC 7541 (HPACK): the static table (Appendix A) and
the Huffman code (Appendix B), so the tables come from the RFC, not from the code under test.

    curl -o rfc7541.txt https://www.rfc-editor.org/rfc/rfc7541.txt
    python3 tools/gen_hpack_tables.py rfc7541.txt

It checks what it reads: 61 static entries numbered 1-61; 257 Huffman codes, each bit string equal to its hex form
and length, forming a canonical code (which the decoder relies on). The output's first line says it is generated.
"""

import hashlib
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "packages", "web_http2", "src", "tables.cee")


def static_table(text):
    start = text.index("Appendix A.  Static Table Definition")
    body = text[start:text.index("Appendix B.", start)]
    rows = re.findall(r"^\s*\|\s*(\d+)\s+\|\s*(\S+)\s*\|\s*(.*?)\s*\|\s*$", body, re.M)
    entries = [(int(i), name, value) for i, name, value in rows]
    assert [e[0] for e in entries] == list(range(1, 62)), "the static table is not entries 1-61"
    return [(name, value) for _, name, value in entries]


def huffman(text):
    start = text.index("Appendix B.  Huffman Code")
    rows = re.findall(r"\(\s*(\d+)\)\s+\|([01|]+)\s+([0-9a-f]+)\s+\[\s*(\d+)\]", text[start:])
    codes = {}
    for symbol, bits, hexa, length in rows:
        bits = bits.replace("|", "")
        assert int(bits, 2) == int(hexa, 16) and len(bits) == int(length), f"symbol {symbol}: bits and hex differ"
        codes[int(symbol)] = (int(hexa, 16), int(length))
    assert sorted(codes) == list(range(257)), "the Huffman code does not cover symbols 0-256"
    order = sorted(range(257), key=lambda s: (codes[s][1], codes[s][0]))
    for a, b in zip(order, order[1:]):
        (ca, la), (cb, lb) = codes[a], codes[b]
        assert cb == (ca + 1) << (lb - la), "the Huffman code is not canonical"
    return codes, order


def array(name, kind, values, per_line=12):
    lines = [f"const {name}: [{kind}; {len(values)}] = ["]
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("];")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    raw = open(sys.argv[1], "rb").read()
    text = raw.decode("ascii")
    digest = hashlib.sha256(raw).hexdigest()
    table = static_table(text)
    codes, order = huffman(text)

    blob, name_at, name_len, value_at, value_len = "", [0], [0], [0], [0]
    for name, value in table:
        name_at.append(len(blob)); name_len.append(len(name)); blob += name
        value_at.append(len(blob)); value_len.append(len(value)); blob += value
    assert '"' not in blob and "\\" not in blob

    first_code, first_index, count = [0] * 31, [0] * 31, [0] * 31
    for i, s in enumerate(order):
        code, length = codes[s]
        if count[length] == 0:
            first_code[length], first_index[length] = code, i
        count[length] += 1

    out = [
        "// Generated by tools/gen_hpack_tables.py from RFC 7541's text (sha256 " + digest[:16] + "…); do not edit.",
        "// The static table (Appendix A) and the Huffman code (Appendix B).",
        "",
        "/// The static table's names and values, one after another; `STATIC_NAME_AT` and the others index it.",
        f'fn staticText() -> StringView => "{blob}";',
        "",
        "/// Entries 1-61 (index 0 is unused): where each name and value starts in `staticText()`, and its length.",
        array("STATIC_NAME_AT", "u16", name_at),
        array("STATIC_NAME_LEN", "u8", name_len),
        array("STATIC_VALUE_AT", "u16", value_at),
        array("STATIC_VALUE_LEN", "u8", value_len),
        "",
        "/// Each symbol's code (0-255 the octets, 256 EOS), right-aligned, and its length in bits.",
        array("HUFFMAN_CODE", "u32", [codes[s][0] for s in range(257)], 8),
        array("HUFFMAN_LENGTH", "u8", [codes[s][1] for s in range(257)], 16),
        "",
        "/// The canonical code's symbols in code order (by length, then code), and for each length 0-30 its first code,",
        "/// where its symbols start in `HUFFMAN_SYMBOLS`, and how many there are.",
        array("HUFFMAN_SYMBOLS", "u16", order, 16),
        array("HUFFMAN_FIRST_CODE", "u32", first_code, 8),
        array("HUFFMAN_FIRST_INDEX", "u16", first_index, 16),
        array("HUFFMAN_COUNT", "u16", count, 16),
        "",
    ]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    ceesafec = os.environ.get("CEESAFEC", "ceesafec")
    subprocess.run([ceesafec, "fmt", OUT], check=True)
    print(f"gen_hpack_tables: wrote {os.path.relpath(OUT, ROOT)}: 61 static entries, 257 Huffman codes "
          f"(RFC 7541 sha256 {digest})")


if __name__ == "__main__":
    main()
