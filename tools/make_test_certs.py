"""Generates web_tls's test certificates (Web ADR 0002 §5) with the openssl CLI, and writes them as CeeSafe constants
to packages/web_tls/tests/certs.cee, and as PEM files to packages/web_tls/tests/certs/ for the interop tests.

Test material only: these keys protect nothing. Rerun to replace them (the keys change every run):
    python3 tools/make_test_certs.py [--openssl /opt/homebrew/opt/openssl@3/bin/openssl]

  ca            the test CA (EC P-256)
  server        localhost, 127.0.0.1 and ::1, signed by ca, valid 2026-01-01 to 2126-01-01
  expired       localhost, signed by ca, valid 2020-01-01 to 2021-01-01
  future        localhost, signed by ca, valid from 2120-01-01
  wronghost     example.com only, signed by ca
  other-ca      a second CA, which nothing trusts
  stranger      localhost, signed by other-ca
  client        a client certificate (CN "test client", extendedKeyUsage clientAuth), signed by ca
"""
import argparse, pathlib, subprocess, tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "packages/web_tls/tests"


def run(openssl, *args, cwd):
    subprocess.run([openssl, *args], cwd=cwd, check=True, capture_output=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--openssl", default="/opt/homebrew/opt/openssl@3/bin/openssl")
    o = ap.parse_args().openssl
    with tempfile.TemporaryDirectory() as d:
        w = pathlib.Path(d)

        def key(name):
            run(o, "genpkey", "-algorithm", "EC", "-pkeyopt", "ec_paramgen_curve:P-256", "-out", f"{name}.key", cwd=w)

        def ca(name, cn):
            key(name)
            run(o, "req", "-x509", "-new", "-key", f"{name}.key", "-subj", f"/CN={cn}", "-out", f"{name}.pem",
                "-not_before", "20260101000000Z", "-not_after", "21260101000000Z",
                "-addext", "basicConstraints=critical,CA:TRUE", "-addext", "keyUsage=critical,keyCertSign,cRLSign",
                cwd=w)

        def leaf(name, issuer, cn, san, start, end, usage="serverAuth"):
            key(name)
            run(o, "req", "-new", "-key", f"{name}.key", "-subj", f"/CN={cn}", "-out", f"{name}.csr", cwd=w)
            ext = w / f"{name}.ext"
            lines = ["basicConstraints=critical,CA:FALSE", "keyUsage=critical,digitalSignature",
                     f"extendedKeyUsage={usage}"]
            if san:
                lines.append(f"subjectAltName={san}")
            ext.write_text("\n".join(lines) + "\n")
            run(o, "x509", "-req", "-in", f"{name}.csr", "-CA", f"{issuer}.pem", "-CAkey", f"{issuer}.key",
                "-set_serial", str(abs(hash(name)) % 10**12), "-not_before", start, "-not_after", end,
                "-extfile", ext.name, "-out", f"{name}.pem", cwd=w)

        ca("ca", "CeeSafe.Web test CA")
        ca("other-ca", "Untrusted test CA")
        always = ("20260101000000Z", "21260101000000Z")
        local = "DNS:localhost,IP:127.0.0.1,IP:::1"
        leaf("server", "ca", "localhost", local, *always)
        leaf("expired", "ca", "localhost", local, "20200101000000Z", "20210101000000Z")
        leaf("future", "ca", "localhost", local, "21200101000000Z", "21260101000000Z")
        leaf("wronghost", "ca", "example.com", "DNS:example.com", *always)
        leaf("stranger", "other-ca", "localhost", local, *always)
        leaf("client", "ca", "test client", None, *always, usage="clientAuth")

        names = ["ca", "server", "expired", "future", "wronghost", "other-ca", "stranger", "client"]
        (OUT / "certs").mkdir(parents=True, exist_ok=True)
        cee = ["// Generated by tools/make_test_certs.py: web_tls's test certificates and keys (test material only).",
               "// Each `<name>Pem` is the certificate; each `<name>Key` its private key (PKCS #8).", ""]
        for n in names:
            pem = (w / f"{n}.pem").read_text()
            k = (w / f"{n}.key").read_text()
            (OUT / "certs" / f"{n}.pem").write_text(pem)
            (OUT / "certs" / f"{n}.key").write_text(k)
            ident = "".join(p.capitalize() if i else p for i, p in enumerate(n.split("-")))
            cee.append(f"fn {ident}Pem() -> StringView => {cee_string(pem)};")
            cee.append("")
            cee.append(f"fn {ident}Key() -> StringView => {cee_string(k)};")
            cee.append("")
        (OUT / "certs.cee").write_text("\n".join(cee))
    print(f"wrote {OUT / 'certs.cee'} and {OUT / 'certs'}/")


def cee_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


if __name__ == "__main__":
    main()
